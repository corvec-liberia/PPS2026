const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..', 'pwa');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const files = fs.readdirSync(root);

assert.ok(files.includes('manifest.webmanifest'));
assert.ok(files.includes('sw.js'));
assert.ok(files.includes('icon.svg'));
assert.ok(files.includes('icon-192.png'));
assert.ok(files.includes('icon-512.png'));
const index = read('index.html');
const app = read('app.js');
const admin = read('admin.js');
const adminPage = read('admin.html');
const sw = read('sw.js');
const manifest = JSON.parse(read('manifest.webmanifest'));
assert.ok(index.includes('Encuesta de'));
assert.ok(index.includes('Empleabilidad 2026'));
assert.ok(index.includes('Esperamos que su experiencia durante la práctica profesional haya sido agradable'));
assert.ok(index.includes('Máster Óscar Campos Rodríguez'));
assert.ok(index.includes('id="verifiedSpecialty"') && index.includes('id="verifiedStudent"'));
assert.ok((index.match(/readonly/g) || []).length >= 2);
assert.ok(!index.includes('id="accessCode"') && !index.includes('Ingrese su código personal'));
assert.ok(index.includes('id="retryIdentityButton"'));
for (const phrase of ['Continuación de estudios', 'Otra oportunidad laboral', 'Motivos personales', 'Condiciones laborales', 'Otro motivo']) assert.ok(index.includes(phrase));
assert.ok(index.includes('referrer'));
assert.ok(app.includes("jsonp('result', { rid })"));
assert.ok(app.includes('result.stored'));
assert.ok(app.includes('Sin conexión'));
assert.ok(app.includes("action: 'identify'"));
assert.ok(app.includes("params.get('c')"));
assert.ok(app.includes('verifyCode(personalCode)'));
assert.ok(!app.includes("jsonp('specialties'"));
assert.ok(admin.includes("action: 'adminLogin'"));
assert.ok(admin.includes('accessLinks'));
assert.ok(admin.includes('25 * 60 * 1000'));
assert.ok(admin.includes('function lockAdminPanel'));
assert.ok(adminPage.includes('id="refreshButton"'));
assert.ok(adminPage.includes('id="specialtyChart"'));
assert.ok(adminPage.includes('id="companyChart"'));
assert.ok(adminPage.includes('id="filterSpecialty"'));
assert.ok(adminPage.includes('id="filterCompany"'));
assert.ok(!/google\.script\.run|\bCEDULA\s*:/i.test(index + app + admin));
assert.ok(sw.includes('request.mode === \'navigate\''));
assert.ok(sw.includes("pathname.endsWith('/config.js')"));
assert.ok(sw.includes('pps-empleabilidad-2026-v3'));
assert.ok(sw.includes('fetch(request).then(response =>'));
assert.equal(manifest.display, 'standalone');
assert.ok(manifest.icons.some(icon => icon.sizes === '192x192'));
assert.ok(manifest.icons.some(icon => icon.sizes === '512x512'));
console.log('Passed static PWA safety, offline and installability checks.');
